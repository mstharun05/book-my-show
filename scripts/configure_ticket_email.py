"""Local, masked credential entry; no secrets are printed or passed as arguments."""
import json
from pathlib import Path
import tkinter as tk
from tkinter import messagebox
import webbrowser

config_path = Path(__file__).resolve().parent.parent / 'delivery.local.json'
initial_config = json.loads(config_path.read_text(encoding='utf-8')) if config_path.exists() else {}
root = tk.Tk()
root.title('Book My Show - Gmail setup')
root.geometry('550x300')
tk.Label(root, text='Gmail ticket sender', font=('Arial', 13, 'bold')).pack(pady=10)
sender = tk.Entry(root, width=40)
sender.insert(0, initial_config.get('EMAIL_HOST_USER', ''))
sender.pack()
tk.Label(root, text='Create a Google app password named Book My Show.\nPaste it below. Do not enter your normal Gmail password.').pack()
tk.Button(root, text='Open Google App Passwords', command=lambda: webbrowser.open('https://myaccount.google.com/apppasswords')).pack(pady=10)
password = tk.Entry(root, show='*', width=35)
password.pack()


def save():
    address = sender.get().strip()
    if not address.endswith('@gmail.com') or len(address.split('@')) != 2:
        messagebox.showerror('Check sender', 'Enter your Gmail address.')
        return
    value = ''.join(password.get().split())
    if len(value) != 16 or not value.isalpha():
        messagebox.showerror('Check app password', 'Enter the 16-letter app password generated by Google.')
        return
    config = json.loads(config_path.read_text(encoding='utf-8')) if config_path.exists() else {}
    config.update(EMAIL_HOST='smtp.gmail.com', EMAIL_PORT='587', EMAIL_USE_TLS='True',
                  EMAIL_USE_SSL='False', EMAIL_HOST_USER=address,
                  DEFAULT_FROM_EMAIL=f'Book My Show <{address}>', EMAIL_HOST_PASSWORD=value)
    config_path.write_text(json.dumps(config, indent=2), encoding='utf-8')
    password.delete(0, tk.END)
    messagebox.showinfo('Saved', 'Saved privately in delivery.local.json (excluded from Git).\nTell Codex: saved. It will test the connection next.')
    root.destroy()


tk.Button(root, text='Save app password', command=save).pack(pady=12)
tk.Label(root, text='Stored locally in the project; never sent to chat.').pack()
root.mainloop()
